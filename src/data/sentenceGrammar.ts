import { GrammarLesson, LanguageCode } from '../types';

// Authored phrase boundaries: Japanese particles and European verb groups
// remain meaningful units, rather than being split into individual characters.
function topic(lang: LanguageCode, index: number, title: string, level: 1 | 2 | 3,
  explanation: string, parts: string[], roles: string[], ru: string,
  transform: [string, string, string], alternatives: string[] = []): GrammarLesson {
  return {
    id: `${lang}-sentence-${index}`, title, level, explanation,
    examples: [{
      target: parts.join(lang === 'ja' ? '' : ' '), ru,
      chunks: parts.map((text, i) => ({ text, role: roles[i] })),
      alternatives,
      transform: { prompt: transform[0], answer: transform[1], explanation: transform[2] },
    }],
  };
}

