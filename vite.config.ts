import { defineConfig, loadEnv } from 'vite'
import react from '@vitejs/plugin-react'
import { spawn } from 'node:child_process'
import { readdirSync } from 'node:fs'
import { join } from 'node:path'

/**
 * The offline service worker, generated at build time with the exact list of
 * emitted assets. Hand-rolled instead of a Workbox dependency: the behaviour
 * the app needs is small (precache the shell, network-first navigation,
 * stale-while-revalidate fonts) and the Android shell must never get one —
 * see `src/services/pwa.ts`.
 *
 * Bump CACHE_VERSION whenever this script itself changes, so old clients pick
 * the new worker up even if no asset changed.
 */
const SERVICE_WORKER_VERSION = 'v1';

const buildServiceWorkerScript = (precacheUrls: string[], indexUrl: string): string => `
'use strict';
// Generated by the pwa-service-worker plugin in vite.config.ts. Do not edit
// the emitted file: it is rebuilt from this template on every build.
var CACHE_NAME = 'pogruzhenie-${SERVICE_WORKER_VERSION}';
var FONT_CACHE_NAME = 'pogruzhenie-fonts-${SERVICE_WORKER_VERSION}';
var PRECACHE_URLS = ${JSON.stringify(precacheUrls)};
var INDEX_URL = ${JSON.stringify(indexUrl)};
var FONT_ORIGINS = ['https://fonts.googleapis.com', 'https://fonts.gstatic.com'];
var MAX_FONT_ENTRIES = 30;

function trimCache(cache, maxEntries) {
  return cache.keys().then(function (keys) {
    if (keys.length <= maxEntries) return undefined;
    return Promise.all(
      keys.slice(0, keys.length - maxEntries).map(function (key) { return cache.delete(key); })
    );
  });
}

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(function (cache) {
        return Promise.allSettled(PRECACHE_URLS.map(function (url) { return cache.add(url); }));
      })
      .then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys()
      .then(function (keys) {
        return Promise.all(
          keys
            .filter(function (key) { return key !== CACHE_NAME && key !== FONT_CACHE_NAME; })
            .map(function (key) { return caches.delete(key); })
        );
      })
      .then(function () { return caches.open(CACHE_NAME); })
      .then(function (cache) {
        return cache.keys().then(function (requests) {
          return Promise.all(
            requests
              .filter(function (request) { return PRECACHE_URLS.indexOf(new URL(request.url).pathname) === -1; })
              .map(function (request) { return cache.delete(request); })
          );
        });
      })
      .then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('fetch', function (event) {
  var request = event.request;
  if (request.method !== 'GET') return;
  var url = new URL(request.url);

  // Navigation: a fresh deploy when online, the cached shell when offline.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).then(function (response) {
        var copy = response.clone();
        caches.open(CACHE_NAME).then(function (cache) {
          cache.put(INDEX_URL, copy).catch(function () {});
        }).catch(function () {});
        return response;
      }).catch(function () { return caches.match(INDEX_URL); })
    );
    return;
  }

  // Google Fonts: serve from cache, refresh in the background.
  if (FONT_ORIGINS.indexOf(url.origin) !== -1) {
    event.respondWith(
      caches.open(FONT_CACHE_NAME).then(function (cache) {
        return cache.match(request).then(function (cached) {
          var network = fetch(request).then(function (response) {
            if (response.ok) {
              cache.put(request, response.clone()).then(function () {
                return trimCache(cache, MAX_FONT_ENTRIES);
              }).catch(function () {});
            }
            return response;
          }).catch(function () { return cached; });
          return cached || network;
        });
      })
    );
    return;
  }

  // App-shell assets (content-hashed names): cache-first, network fallback.
  if (url.origin === self.location.origin && PRECACHE_URLS.indexOf(url.pathname) !== -1) {
    event.respondWith(
      caches.match(request).then(function (cached) {
        if (cached) return cached;
        return fetch(request).then(function (response) {
          if (response.ok) {
            caches.open(CACHE_NAME).then(function (cache) {
              cache.put(request, response.clone()).catch(function () {});
            }).catch(function () {});
          }
          return response;
        });
      })
    );
  }
});
`;

// https://vitejs.dev/config/
export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), '');
  const azureSpeechKey = env.AZURE_SPEECH_KEY;
  const azureSpeechRegion = env.AZURE_SPEECH_REGION;
  const azureSpeechVoice = env.AZURE_SPEECH_VOICE || 'sk-SK-ViktoriaNeural';
  const edgeTtsPython = env.EDGE_TTS_PYTHON || 'python';
  const edgeTtsVoices: Record<string, string> = {
    en: env.EDGE_TTS_EN_VOICE || 'en-US-EmmaNeural',
    es: env.EDGE_TTS_ES_VOICE || 'es-ES-ElviraNeural',
    de: env.EDGE_TTS_DE_VOICE || 'de-DE-KatjaNeural',
    fr: env.EDGE_TTS_FR_VOICE || 'fr-FR-DeniseNeural',
    it: env.EDGE_TTS_IT_VOICE || 'it-IT-ElsaNeural',
    ja: env.EDGE_TTS_JA_VOICE || 'ja-JP-NanamiNeural',
    sk: env.EDGE_TTS_VOICE || 'sk-SK-ViktoriaNeural',
    cs: env.EDGE_TTS_CS_VOICE || 'cs-CZ-VlastaNeural',
    he: env.EDGE_TTS_HE_VOICE || 'he-IL-HilaNeural',
    kk: env.EDGE_TTS_KK_VOICE || 'kk-KZ-AigulNeural'
  };
  const edgeTtsRate = env.EDGE_TTS_RATE || '-12%';

  // The base the build is served from ('/' on the web, '/assets/www/' in the
  // Android shell). The service-worker plugin fills it in from the resolved
  // config so precache URLs are correct for either target.
  let resolvedBase = '/';
  // `public/` files are copied to dist after generateBundle runs, so they are
  // not in the bundle object yet — the plugin reads the directory itself.
  let publicDir = 'public';

  const synthesizeWithEdgeTts = (text: string, lang: string): Promise<Buffer> => new Promise((resolve, reject) => {
    const voice = edgeTtsVoices[lang];
    if (!voice) {
      reject(new Error(`No Edge-TTS voice configured for ${lang}`));
      return;
    }
    const child = spawn(edgeTtsPython, [
      '-m', 'edge_tts',
      '--text', text,
      '--voice', voice,
      `--rate=${edgeTtsRate}`
    ], { windowsHide: true });
    const chunks: Buffer[] = [];
    let errorOutput = '';

    child.stdout.on('data', (chunk: Buffer) => chunks.push(chunk));
    child.stderr.on('data', (chunk: Buffer) => { errorOutput += chunk.toString(); });
    child.on('error', reject);
    child.on('close', (code) => {
      if (code === 0 && chunks.length > 0) {
        resolve(Buffer.concat(chunks));
      } else {
        reject(new Error(errorOutput.trim() || `edge-tts exited with code ${code}`));
      }
    });
  });

  return ({
  build: {
    rollupOptions: {
      output: {
        // Split the two heaviest, slowest-changing dependencies out of the
        // entry chunk. React changes only when the app upgrades it, and the
        // Supabase SDK is loaded lazily (see services/supabase.ts), so both
        // chunks keep their hash — and the browser cache — across app deploys
        // instead of being re-downloaded with every release.
        manualChunks: {
          'vendor-react': ['react', 'react-dom'],
          'vendor-supabase': ['@supabase/supabase-js'],
        },
      },
    },
  },
  plugins: [
    react(),
    {
      // Emits dist/sw.js with the exact precache list for this build. Only
      // in `vite build`: the dev server has no built assets to precache, and
      // the Android shell never registers the worker (see services/pwa.ts).
      name: 'pwa-service-worker',
      apply: 'build',
      configResolved(config) {
        resolvedBase = config.base;
        publicDir = config.publicDir;
      },
      generateBundle(_options, bundle) {
        const joinUrl = (name: string): string =>
          resolvedBase.endsWith('/') ? `${resolvedBase}${name}` : `${resolvedBase}/${name}`;
        const isPrecacheable = (name: string): boolean => /\.(?:html|js|css|webmanifest|png|svg)$/.test(name);
        const collectPublic = (dir: string, prefix: string): string[] => {
          const found: string[] = [];
          for (const entry of readdirSync(dir, { withFileTypes: true })) {
            const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
            if (entry.isDirectory()) found.push(...collectPublic(join(dir, entry.name), rel));
            else if (isPrecacheable(rel)) found.push(rel);
          }
          return found;
        };
        const urls = Array.from(new Set([
          ...Object.keys(bundle).filter(isPrecacheable),
          ...collectPublic(publicDir, ''),
        ]))
          .map(joinUrl)
          .sort();
        const indexUrl = joinUrl('index.html');
        if (!urls.includes(indexUrl)) urls.push(indexUrl);
        this.emitFile({ type: 'asset', fileName: 'sw.js', source: buildServiceWorkerScript(urls, indexUrl) });
      },
    },
    {
      name: 'tts-proxy-plugin',
      configureServer(server) {
        server.middlewares.use('/api/tts', (req, res) => {
          try {
            const urlObj = new URL(req.url || '', 'http://localhost');
            const text = urlObj.searchParams.get('text') || '';
            const lang = (urlObj.searchParams.get('lang') || 'ja').toLowerCase();

            if (!text.trim()) {
              res.statusCode = 400;
              res.end('Missing text');
              return;
            }

            if (text.length > 500) {
              res.statusCode = 413;
              res.end('Text is too long');
              return;
            }

            // Same whitelist as production (api/tts.py VOICES keys): an unknown
            // language must fail loudly instead of silently reading the text
            // with the Japanese voice.
            if (!Object.prototype.hasOwnProperty.call(edgeTtsVoices, lang)) {
              res.statusCode = 400;
              res.end('Unsupported language');
              return;
            }

            const targetLang = lang;

            const sendAudio = (audioBuffer: Buffer) => {
              res.setHeader('Content-Type', 'audio/mpeg');
              res.setHeader('X-Content-Type-Options', 'nosniff');
              // Text is user supplied, so keep it out of shared caches.
              res.setHeader('Cache-Control', 'private, max-age=3600');
              res.end(audioBuffer);
            };

            const fetchGoogleTts = async (): Promise<Buffer> => {
              const googleUrl = `https://translate.google.com/translate_tts?ie=UTF-8&q=${encodeURIComponent(text)}&tl=${targetLang}&client=tw-ob`;
              let response = await fetch(googleUrl, {
                headers: {
                  'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
                }
              });
              if (!response.ok) {
                const youdaoLang = targetLang === 'ja' ? 'jap' : targetLang;
                const youdaoUrl = `https://dict.youdao.com/dictvoice?audio=${encodeURIComponent(text)}&le=${youdaoLang}`;
                response = await fetch(youdaoUrl);
              }
              if (!response.ok) throw new Error(`Fallback TTS ${response.status}`);
              return Buffer.from(await response.arrayBuffer());
            };

            const fetchAzureTts = async (): Promise<Buffer> => {
              if (!azureSpeechKey || !azureSpeechRegion) throw new Error('Azure TTS is not configured');
              const escapeXml = (value: string) => value
                .replace(/&/g, '&amp;')
                .replace(/</g, '&lt;')
                .replace(/>/g, '&gt;')
                .replace(/"/g, '&quot;')
                .replace(/'/g, '&apos;');
              const ssml = `<speak version="1.0" xml:lang="sk-SK"><voice name="${escapeXml(azureSpeechVoice)}">${escapeXml(text)}</voice></speak>`;
              const response = await fetch(`https://${azureSpeechRegion}.tts.speech.microsoft.com/cognitiveservices/v1`, {
                method: 'POST',
                headers: {
                  'Ocp-Apim-Subscription-Key': azureSpeechKey,
                  'Content-Type': 'application/ssml+xml',
                  'X-Microsoft-OutputFormat': 'audio-24khz-96kbitrate-mono-mp3'
                },
                body: ssml
              });
              if (!response.ok) throw new Error(`Azure TTS ${response.status}`);
              return Buffer.from(await response.arrayBuffer());
            };

            synthesizeWithEdgeTts(text, targetLang)
              .catch(async (edgeError) => {
                console.warn('Edge-TTS unavailable, trying fallback:', edgeError.message);
                if (lang === 'sk' && azureSpeechKey && azureSpeechRegion) {
                  try {
                    return await fetchAzureTts();
                  } catch (azureError) {
                    console.warn('Azure TTS unavailable, using Google fallback:', azureError);
                  }
                }
                return fetchGoogleTts();
              })
              .then(sendAudio)
              .catch((error) => {
                console.error('Server TTS proxy error:', error);
                res.statusCode = 502;
                res.end('TTS providers unavailable');
              });
          } catch (e) {
            res.statusCode = 500;
            res.end('Error');
          }
        });
      }
    }
  ],
  server: {
    port: 3000,
    open: true
  }
  });
});
